using System.Text;
using ContributionArt.Features.Shared;

namespace ContributionArt.Features.ScriptExport
{
    /// <summary>Produces a gitfiti-style bash script, for people who prefer to run git themselves.</summary>
    public static class ScriptExporter
    {
        public static string Bash(string owner, string repository, string authorName, string authorEmail,
            DateOnly readmeDate, IReadOnlyList<CommitPlanItem> plan)
        {
            var sb = new StringBuilder();
            sb.AppendLine("#!/usr/bin/env bash");
            sb.AppendLine("# Generated by Contribution Art. Run it from a folder that is NOT inside a git repository.");
            sb.AppendLine("# Requires: git 2.28+, SSH access to GitHub, and an empty repository already created on GitHub.");
            sb.AppendLine("set -euo pipefail");
            sb.AppendLine();
            sb.AppendLine($"REPO={Quote(repository)}");
            sb.AppendLine("git init -q -b main \"$REPO\"");
            sb.AppendLine("cd \"$REPO\"");
            sb.AppendLine($"git config user.name {Quote(authorName)}");
            sb.AppendLine($"git config user.email {Quote(authorEmail)}");
            sb.AppendLine();
            sb.AppendLine("cat > README.md <<'EOF'");
            sb.Append(PublishedReadme.Text);
            sb.AppendLine("EOF");
            sb.AppendLine("git add README.md");
            sb.AppendLine($"GIT_AUTHOR_DATE={Stamp(readmeDate)} GIT_COMMITTER_DATE={Stamp(readmeDate)} " +
                          "git commit -q -m \"Add README: this repository is contribution-graph art\"");
            sb.AppendLine();
            sb.AppendLine("paint() { # $1 = ISO date, $2 = number of commits");
            sb.AppendLine("  for _ in $(seq 1 \"$2\"); do");
            sb.AppendLine("    GIT_AUTHOR_DATE=\"$1\" GIT_COMMITTER_DATE=\"$1\" git commit -q --allow-empty -m \"contribution-art\"");
            sb.AppendLine("  done");
            sb.AppendLine("}");
            sb.AppendLine();

            foreach (var item in plan.OrderBy(p => p.Date))
            {
                sb.AppendLine($"paint {Stamp(item.Date)} {item.Commits}");
            }

            sb.AppendLine();
            sb.AppendLine($"git remote add origin git@github.com:{owner}/{repository}.git");
            sb.AppendLine("git push -u origin main");
            return sb.ToString();
        }

        private static string Stamp(DateOnly date) => $"{date:yyyy-MM-dd}T12:00:00+00:00";

        private static string Quote(string value) => "'" + value.Replace("'", "'\\''") + "'";
    }
}
